interface AppPlatformResource {
  apiVersion: string;
  kind: string;
  metadata: {
    name: string;
    namespace: string;
    uid: string;
    resourceVersion: string;
    creationTimestamp: string;
    annotations: Record<string, string>;
    labels: Record<string, string>;
  };
  spec: {
    id: string;
    title: string;
    schemaVersion: string;
    blocks: Array<{ id?: string; type?: string; content?: string; [key: string]: unknown }>;
    status: 'draft' | 'published';
    manifest: {
      author?: { name?: string; team?: string };
      additionalFields?: Record<string, unknown>;
      [key: string]: unknown;
    };
    [key: string]: unknown;
  };
}

interface BackendRequest {
  url: string;
  method?: string;
  data?: AppPlatformResource;
}

const EDITOR_OWNED_SPEC_FIELDS = new Set(['id', 'title', 'schemaVersion', 'blocks', 'status', 'manifest']);

let finalizedResource: AppPlatformResource;
let storedResource: AppPlatformResource;

jest.setTimeout(15_000);

function clone<T>(value: T): T {
  return JSON.parse(JSON.stringify(value)) as T;
}

async function resourceFromFinalize(): Promise<AppPlatformResource> {
  const server = buildServer();
  const [serverTransport, clientTransport] = InMemoryTransport.createLinkedPair();
  await server.connect(serverTransport);
  const client = new Client({ name: 'block-editor-manifest-test', version: '0' }, { capabilities: {} });
  await client.connect(clientTransport);
  try {
    const result = await client.callTool({
      name: 'pathfinder_finalize_for_app_platform',
      arguments: {
        status: 'draft',
        artifact: {
          content: {
            id: 'assistant-guide',
            schemaVersion: CURRENT_SCHEMA_VERSION,
            title: 'Assistant guide',
            type: 'guide',
            blocks: [{ id: 'intro', type: 'markdown', content: 'Assistant-authored introduction' }],
          },
          manifest: {
            id: 'assistant-guide',
            schemaVersion: CURRENT_SCHEMA_VERSION,
            type: 'guide',
            repository: 'interactive-tutorials',
            description: 'A rich guide generated by Assistant',
            category: 'onboarding',
            author: { name: 'pathfinder-mcp', team: 'Docs enablement' },
            depends: ['grafana-basics'],
            startingLocation: '/explore',
            difficulty: 'beginner',
          },
        },
      },
    });
    const text = (result.content as Array<{ type: string; text?: string }>).find((item) => item.type === 'text')?.text;
    const payload = JSON.parse(text ?? '{}') as { status?: string; resource?: AppPlatformResource };
    expect(payload.status).toBe('ready');
    expect(payload.resource).toBeDefined();
    return {
      ...payload.resource!,
      metadata: {
        ...payload.resource!.metadata,
        namespace: 'stacks-1',
        uid: 'assistant-guide-uid',
        resourceVersion: '42',
        creationTimestamp: '2026-11-07T00:00:00Z',
        annotations: {
          'pathfinderbackend.ext.grafana.app/managed-by': 'grafana-assistant',
          'pathfinderbackend.ext.grafana.app/source-session': 'session-2309',
        },
        labels: { origin: 'assistant', tier: 'gold' },
      },
      spec: {
        ...payload.resource!.spec,
        assistantHandoff: { session: 'session-2309', retained: true },
      },
    };
  } finally {
    await client.close();
    await server.close();
  }
}

function putBodies(): AppPlatformResource[] {
  return mockFetch.mock.calls
    .map(([request]) => request as BackendRequest)
    .filter((request) => request.method === 'PUT')
    .map((request) => request.data!);
}

function assertPreservedWrite(body: AppPlatformResource, status: 'draft' | 'published', content: string): void {
  expect(body.metadata.annotations).toEqual(finalizedResource.metadata.annotations);
  expect(body.metadata.labels).toEqual(finalizedResource.metadata.labels);

  const unownedSpec = Object.fromEntries(
    Object.entries(body.spec).filter(([key]) => !EDITOR_OWNED_SPEC_FIELDS.has(key))
  );
  const storedUnownedSpec = Object.fromEntries(
    Object.entries(finalizedResource.spec).filter(([key]) => !EDITOR_OWNED_SPEC_FIELDS.has(key))
  );
  expect(unownedSpec).toEqual(storedUnownedSpec);
  const stored = finalizedResource.spec.manifest;
  // Manifest ownership for this round trip: replace a placeholder author name, recompute guide
  // stats, default a missing type or repository, and preserve an externally authored startingLocation.
  expect(body.spec.manifest).toEqual({
    ...stored,
    type: stored.type ?? 'guide',
    repository: stored.repository ?? 'app-platform',
    author: { ...stored.author, name: 'Sam Rivera' },
    additionalFields: {
      ...stored.additionalFields,
      stats: expect.objectContaining({ blockCount: 1, sectionCount: 0 }),
    },
  });
  expect(body.spec.status).toBe(status);
  expect(body.spec.blocks[0]?.content).toBe(content);
}

async function openLibraryAndLoad(): Promise<ReturnType<typeof render>> {
  const view = render(<BlockEditor />);
  await screen.findByTestId(testIds.blockEditor.moreActionsButton);
  fireEvent.click(screen.getByTestId(testIds.blockEditor.moreActionsButton));
  fireEvent.click(await screen.findByTestId(testIds.blockEditor.libraryButton));
  const library = await screen.findByRole('dialog', { name: 'Guide library' });
  fireEvent.click(within(library).getByRole('button', { name: 'Load' }));
  await screen.findByText('Assistant-authored introduction');
  return view;
}

async function editMarkdown(content: string): Promise<void> {
  fireEvent.click(screen.getByTestId(testIds.blockEditor.editButton));
  fireEvent.click(await screen.findByTestId(testIds.blockEditor.rawMarkdownTab));
  fireEvent.change(screen.getByTestId(testIds.blockEditor.markdownTextarea), { target: { value: content } });
  fireEvent.click(screen.getByTestId(testIds.blockEditor.submitButton));
  await screen.findByText(content);
}

async function saveAndWaitForPut(expectedCount: number): Promise<AppPlatformResource> {
  fireEvent.click(screen.getByTestId(testIds.blockEditor.saveDraftButton));
  await waitFor(() => expect(putBodies()).toHaveLength(expectedCount));
  return putBodies()[expectedCount - 1]!;
}

beforeAll(async () => {
  finalizedResource = await resourceFromFinalize();
  expect(finalizedResource.spec.manifest).toMatchObject({
    description: 'A rich guide generated by Assistant',
    category: 'onboarding',
    author: { name: 'pathfinder-mcp', team: 'Docs enablement' },
    depends: [['grafana-basics']],
    additionalFields: { difficulty: 'beginner', startingLocation: '/explore' },
  });
});

beforeEach(() => {
  localStorage.clear();
  storedResource = clone(finalizedResource);
  mockFetch.mockReset().mockImplementation((request: BackendRequest) => {
    if (request.method === 'PUT' && request.data) {
      const nextVersion = String(Number(storedResource.metadata.resourceVersion) + 1);
      storedResource = clone({
        ...request.data,
        metadata: { ...request.data.metadata, resourceVersion: nextVersion },
      });
      return of({ data: clone(storedResource) });
    }
    const url = new URL(request.url, 'http://localhost');
    if (url.pathname.endsWith('/custom-guide') && url.searchParams.get('name') === storedResource.metadata.name) {
      return of({ data: clone(storedResource) });
    }
    if (url.pathname.endsWith('/custom-guides')) {
      return of({ data: { items: [clone(storedResource)] } });
    }
    return of({ data: {} });
  });
});

describe('BlockEditor App Platform manifest round trip', () => {
  it('loads through the library modal, edits a block, and saves a draft without losing metadata', async () => {
    await openLibraryAndLoad();
    const content = 'Edited in the visual block form';
    await editMarkdown(content);

    const body = await saveAndWaitForPut(1);

    assertPreservedWrite(body, 'draft', content);
  });

  it('preserves the finalize handoff through publish and unpublish request bodies', async () => {
    await openLibraryAndLoad();
    const content = 'Edited before publishing';
    await editMarkdown(content);
    assertPreservedWrite(await saveAndWaitForPut(1), 'draft', content);

    await screen.findByTestId(testIds.blockEditor.publishButton);
    fireEvent.click(screen.getByTestId(testIds.blockEditor.publishButton));
    await waitFor(() => expect(putBodies()).toHaveLength(2));
    assertPreservedWrite(putBodies()[1]!, 'published', content);

    await screen.findByRole('button', { name: 'Update' });
    fireEvent.click(screen.getByTestId(testIds.blockEditor.moreActionsButton));
    fireEvent.click(await screen.findByTestId(testIds.blockEditor.unpublishButton));
    await waitFor(() => expect(putBodies()).toHaveLength(3));
    assertPreservedWrite(putBodies()[2]!, 'draft', content);
  });

  it('preserves the finalize handoff after an edit made in JSON mode', async () => {
    await openLibraryAndLoad();
    fireEvent.click(screen.getByRole('radio', { name: 'JSON' }));
    const jsonEditor = await screen.findByRole('textbox', { name: 'Guide JSON' });
    const edited = JSON.parse((jsonEditor as HTMLTextAreaElement).value);
    const content = 'Edited in JSON mode';
    edited.blocks[0].content = content;
    fireEvent.change(jsonEditor, { target: { value: JSON.stringify(edited, null, 2) } });
    fireEvent.click(screen.getByRole('radio', { name: 'Edit' }));
    await screen.findByText(content);

    const body = await saveAndWaitForPut(1);

    assertPreservedWrite(body, 'draft', content);
  });

  it('restores the draft and backend tracking after a reload, then preserves the handoff on save', async () => {
    const firstView = await openLibraryAndLoad();
    const content = 'Edited before page reload';
    await editMarkdown(content);
    await waitFor(() => {
      expect(JSON.parse(localStorage.getItem(StorageKeys.BLOCK_EDITOR_BACKEND_TRACKING) ?? '{}')).toMatchObject({
        resourceName: 'assistant-guide',
      });
    });
    firstView.unmount();

    expect(JSON.parse(localStorage.getItem(StorageKeys.BLOCK_EDITOR_STATE) ?? '{}').guide.blocks[0].content).toBe(
      content
    );
    render(<BlockEditor />);
    await screen.findByText(content);

    const body = await saveAndWaitForPut(1);

    assertPreservedWrite(body, 'draft', content);
  });
});
